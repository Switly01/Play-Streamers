// Generates 200-status entry documents for the public SPA routes.
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../', import.meta.url));
const source = await readFile(path.join(root, 'index.html'), 'utf8');
const routes = [
  {
    directory: 'about',
    path: '/about',
    title: 'Hakkımızda · Play Streamers',
    description: 'Play Streamers ve SW CREATE’in yayıncılar için geliştirdiği güvenli, sade ve uzun ömürlü ürün yaklaşımını keşfet.'
  },
  {
    directory: 'products',
    path: '/products',
    title: 'Ürünlerimiz · Play Streamers',
    description: 'Play Streamers Desktop, Play Connect ve yayıncı araçlarını incele; yayın verini tek çalışma alanında yönet.'
  },
  {
    directory: 'how-it-works',
    path: '/how-it-works',
    title: 'Nasıl Çalışır? · Play Streamers',
    description: 'Play Streamers’ın yayın verisini nasıl topladığını, hesapları nasıl koruduğunu ve bağlantıları nasıl yönettiğini öğren.'
  },
  {
    directory: 'play-connect',
    path: '/play-connect',
    title: 'Play Connect · Play Streamers',
    description: 'Play Connect’i Chrome, Microsoft Edge veya Firefox’a ekle; yayın platformlarını Play Streamers hesabına güvenle bağla.'
  }
];

const replaceContent = (html, selectorPattern, value) => html.replace(selectorPattern, match => match.replace(/content="[^"]*"/, `content="${value}"`));

for (const route of routes) {
  const canonical = `https://pstreamers.com${route.path}`;
  let html = source
    .replace(/<title>[\s\S]*?<\/title>/, `<title>${route.title}</title>`)
    .replace(/<link id="psCanonical" rel="canonical" href="[^"]*">/, `<link id="psCanonical" rel="canonical" href="${canonical}">`);
  html = replaceContent(html, /<meta name="description" content="[^"]*">/, route.description);
  html = replaceContent(html, /<meta property="og:title" content="[^"]*">/, route.title);
  html = replaceContent(html, /<meta property="og:description" content="[^"]*">/, route.description);
  html = replaceContent(html, /<meta property="og:url" content="[^"]*">/, canonical);
  html = replaceContent(html, /<meta name="twitter:title" content="[^"]*">/, route.title);
  html = replaceContent(html, /<meta name="twitter:description" content="[^"]*">/, route.description);
  const webPageData = JSON.stringify({
    '@context': 'https://schema.org',
    '@type': 'WebPage',
    '@id': `${canonical}#webpage`,
    url: canonical,
    name: route.title,
    description: route.description,
    isPartOf: { '@id': 'https://pstreamers.com/#website' },
    inLanguage: 'tr'
  });
  html = html.replace('</head>', `<script type="application/ld+json">${webPageData}</script>\n</head>`);
  html = `<!-- Generated by scripts/build-public-route-pages.mjs. Edit index.html or the generator, then rebuild. -->\n${html}`;
  const target = path.join(root, route.directory);
  await mkdir(target, { recursive: true });
  await writeFile(path.join(target, 'index.html'), html);
}

console.log(`Generated ${routes.length} public route pages.`);
